const unscaled: InstructionTable = Object.fromEntries([
	['ldur', 'ldr'], ['stur', 'str'], ['ldurb', 'ldrb'], ['sturb', 'strb'], ['ldurh', 'ldrh'], ['sturh', 'strh'],
	['ldursb', 'ldrsb'], ['ldursh', 'ldrsh'], ['ldursw', 'ldrsw'],
].map(([name, source]) => [name, [DOCS[source][0], `${DOCS[source][1].split('. ')[0].replace(/\.$/, '')}. Use a signed, unscaled byte offset from -256 to 255; no base writeback.`]]))

export function a64InstructionHelp(name: string): InstructionHelp | null {
	const lower = name.toLowerCase()
	if (!isMnemonic(lower)) return null
	const condition = /^b\.?(eq|ne|cs|cc|mi|pl|vs|vc|hi|ls|ge|lt|gt|le|al|nv|hs|lo)$/.exec(lower)
	const entry = condition ? ['target', `Branch when ${conditionCode(condition[1]) === 15 ? 'always' : ARM_CONDITIONS[conditionCode(condition[1])]}.`] : DOCS[lower] ?? unscaled[lower]
	if (!entry) return null
	return formatInstructionHelp(name, {
		summary: entry[1], forms: [`${lower}${entry[0] ? ` ${entry[0]}` : ''}`],
		reference: 'https://developer.arm.com/documentation/ddi0487/latest',
	})
}
