import type { AssemblySource } from '../../../../../core/assembly/sources'

/** Options a corpus case assembles with; `memory` names a configuration. */
export interface CaseOptions {
	delayedBranching?: boolean
	extendedAssembler?: boolean
	warningsAreErrors?: boolean
	memory?: string
}

export interface CorpusCase {
	name: string
	files: string | AssemblySource[]
	entries?: string[] | null
	options?: CaseOptions
}

const single = (name: string, code: string, options?: CaseOptions): CorpusCase => ({ name, files: code, options })

