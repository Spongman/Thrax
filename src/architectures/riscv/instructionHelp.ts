export function riscvInstructionHelp(name: string): InstructionHelp | null {
	const help = tableInstructionHelp(name, DOCS, REFERENCE)
	if (help && name.toLowerCase().startsWith('c.')) help.contents.push('Requires RV32IMC; encoded in 16 bits.')
	return help
}
