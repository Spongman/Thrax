import { beforeAll, describe, expect, it } from 'vitest'
import { initializeArchitecture } from '../../architectures/registry'
import { variantOf } from '../../architectures/contracts'
import { useTHRAXStore } from '../thraxStore'

const state = () => useTHRAXStore.getState()
const errors = () => state().diagnostics.filter(diagnostic => diagnostic.severity === 'error')

beforeAll(async () => { await initializeArchitecture() })

describe('CPU variants in the shared workbench', () => {
	it('switches the 6502 CPU model, rebuilds, and preserves source and per-target choices', async () => {
		expect(await state().switchArchitecture('mos6502')).toBe(true)
		state().setTargetSetting('cpuModel', 'w65c02')
		const source = 'lda #42\nsta $10\nstz $10\nstp'
		state().setCode(source)
		await state().run()
		expect(errors()).toEqual([])
		expect(state().halted).toBe(true)
		expect(state().memory.byte(0x10)).toBe(0)
		state().stepBack()
		expect(state().halted).toBe(false)
		state().stepBack()
		expect(state().memory.byte(0x10)).toBe(42)
		state().setTargetSetting('cpuModel', 'nmos6502')
		expect(state().hasMachine).toBe(false)
		expect(state().executionHistory.length).toBe(0)
		expect(state().code).toBe(source)
		state().assemble()
		expect(errors().length).toBeGreaterThan(0)
		state().setTargetSetting('cpuModel', 'w65c02')
		await state().switchArchitecture('mips')
		await state().switchArchitecture('mos6502')
		expect(state().targetSettings.cpuModel).toBe('w65c02')
		state().setTargetSetting('cpuModel', 'nmos6502')
	})

	it('selects RV32IMC without adding a second target or changing legacy instruction sizes', async () => {
		await state().switchArchitecture('riscv')
		state().setTargetSetting('isa', 'rv32imc')
		const variant = variantOf(state().target!.definition, state().targetSettings)
		expect(variant.examples.compressed).toBeDefined()
		state().setCode(variant.examples.compressed.code)
		await state().run()
		expect(errors()).toEqual([])
		expect(state().console).toBe('42')
		expect(state().halted).toBe(true)
		const first = state().executionHistory.at(0)!
		expect(state().historyFormat!.instruction(first)).toContain('c.addi16sp')
		state().setTargetSetting('isa', 'rv32im')
		expect(state().hasMachine).toBe(false)
		expect(state().executionHistory.length).toBe(0)
		state().assemble()
		expect(errors().some(error => error.message.includes('RV32IMC'))).toBe(true)
	})

	it('stops a running machine when its instruction-set variant changes', async () => {
		await state().switchArchitecture('riscv')
		state().setTargetSetting('isa', 'rv32imc')
		state().setRunSpeed(1000)
		state().setCode('loop: c.j loop')
		const running = state().run()
		await new Promise(resolve => setTimeout(resolve, 20))
		expect(state().isRunning).toBe(true)
		state().setTargetSetting('isa', 'rv32im')
		await running
		expect(state().isRunning).toBe(false)
		expect(state().hasMachine).toBe(false)
		expect(state().executionHistory.length).toBe(0)
		state().setRunSpeed(null)
	})

	it('ignores a step-over completion from the previous CPU variant', async () => {
		await state().switchArchitecture('riscv')
		state().setTargetSetting('isa', 'rv32imc')
		state().setRunSpeed(1000)
		state().setCode('c.jal inner\nc.ebreak\ninner: c.j inner')
		const running = state().stepOver()
		await new Promise(resolve => setTimeout(resolve, 20))
		expect(state().isRunning).toBe(true)
		state().setTargetSetting('isa', 'rv32im')
		await running
		expect(state().isRunning).toBe(false)
		expect(state().isPaused).toBe(false)
		expect(state().hasMachine).toBe(false)
		state().setRunSpeed(null)
	})

	it('selects Cortex-M0 inside ARM and returns to the existing AArch64 profile', async () => {
		await state().switchArchitecture('armv8')
		await state().setTargetSetting('executionState', 'cortex-m0')
		expect(state().targetSettings.executionState).toBe('cortex-m0')
		expect(state().targetVariant!.language).toBe('thrax-thumb-m0')
		expect(state().targetVariant!.registers.some(register => register.id === 'MSP')).toBe(true)
		state().setCode('movs r0,#5\nadds r0,#1\nbkpt #0')
		state().assemble()
		expect(errors()).toEqual([])
		const start = state().pc
		state().step()
		state().step()
		expect(state().registers.R0).toBe(6)
		expect(state().pc).toBe(start + 4)
		state().stepBack()
		expect(state().registers.R0).toBe(5)
		await state().continue()
		expect(state().halted).toBe(true)
		await state().setTargetSetting('executionState', 'aarch64')
		expect(state().hasMachine).toBe(false)
		expect(state().targetVariant!.language).toBe('aarch64')
		expect(state().registers.X0).toBe(0n)
	})

	it('loads 68k and enforces the 68000, 68010 and 68020 model choices', async () => {
		expect(await state().switchArchitecture('m68k')).toBe(true)
		state().setTargetSetting('cpuModel', '68000')
		state().setCode('moveq #5,d1\naddq.l #1,d1\nmoveq #9,d0\ntrap #15')
		state().assemble()
		expect(errors()).toEqual([])
		state().step()
		state().step()
		expect(state().registers.D1).toBe(6)
		state().stepBack()
		expect(state().registers.D1).toBe(5)
		await state().continue()
		expect(state().halted).toBe(true)
		state().setCode('bkpt #0')
		state().assemble()
		expect(errors().length).toBeGreaterThan(0)
		state().setTargetSetting('cpuModel', '68010')
		state().assemble()
		expect(errors()).toEqual([])
		state().setCode('extb.l d1')
		state().assemble()
		expect(errors().length).toBeGreaterThan(0)
		state().setTargetSetting('cpuModel', '68020')
		state().setCode('bra.l end\nnop\nend: moveq #9,d0\ntrap #15')
		await state().run()
		expect(errors()).toEqual([])
		expect(state().halted).toBe(true)
		await state().switchArchitecture('mips')
		await state().switchArchitecture('m68k')
		expect(state().targetSettings.cpuModel).toBe('68020')
	})
})
